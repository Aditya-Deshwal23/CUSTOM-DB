#!/usr/bin/env python3
import argparse
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "src/sql_parser.cpp"
OUTPUT = ROOT / "dashboard/js/sql/keywords.js"


def collect(source: str) -> tuple[list[str], list[str]]:
    keywords = set(re.findall(r'(?:Match|Check|Expect)Keyword\("([A-Z][A-Z0-9_]*)"\)', source))
    keywords.update(
        re.findall(r'EqualsIgnoreCase\([^,\n]+,\s*"([A-Z][A-Z0-9_]*)"', source)
    )
    functions = set(re.findall(r'EqualsIgnoreCase\(expression\.name,\s*"([A-Z][A-Z0-9_]*)"', source))
    keywords.update(functions)
    return sorted(keywords), sorted(functions)


def render(keywords: list[str], functions: list[str]) -> str:
    keyword_source = ", ".join(f'"{item}"' for item in keywords)
    function_source = ", ".join(f'"{item}"' for item in functions)
    return (
        "// Generated by scripts/gen_sql_keywords.py; do not edit by hand.\n"
        f"export const KEYWORDS = new Set([{keyword_source}]);\n"
        f"export const FUNCTIONS = new Set([{function_source}]);\n"
    )


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    expected = render(*collect(SOURCE.read_text(encoding="utf-8")))
    if args.check:
        if not OUTPUT.exists() or OUTPUT.read_text(encoding="utf-8") != expected:
            print(f"{OUTPUT.relative_to(ROOT)} is stale; run python3 scripts/gen_sql_keywords.py",
                  file=sys.stderr)
            return 1
        return 0
    OUTPUT.write_text(expected, encoding="utf-8")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
